// English is the source language: each English sentence is its own key.
// A missing French entry falls back to the English text.

export type Lang = 'en' | 'fr';
export type LangPref = 'auto' | Lang;

export const lang = $state({ code: 'en' as Lang });

export function resolveLang(pref: LangPref | undefined): Lang {
  if (pref === 'en' || pref === 'fr') return pref;
  const sys = (typeof navigator !== 'undefined' && (navigator.languages?.[0] || navigator.language)) || 'en';
  return sys.toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

type Params = Record<string, string | number>;

export function t(s: string, p?: Params): string {
  let out = lang.code === 'fr' ? (FR[s] ?? s) : s;
  if (p) out = out.replace(/\{(\w+)\}/g, (_, k) => (k in p ? String(p[k]) : `{${k}}`));
  return out;
}

/** Plural: French uses the singular for 0 and 1, English only for 1. */
export function tp(n: number, one: string, many: string, p?: Params): string {
  const single = lang.code === 'fr' ? n < 2 : n === 1;
  return t(single ? one : many, { n, ...p });
}

